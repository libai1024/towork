import '../domain/repositories/repository_error.dart';
import 'strings.dart';

String repositoryErrorMessage(RepositoryException error) =>
    switch (error.template) {
      "AI 批次所属表不存在" => strings.parentTableNotFoundForAiBatch,
      "true 或 false" => strings.trueOrFalse,
      "{0}不能为空" => strings.isRequiredRequiretext(error.arguments[0]),
      "「{0}」不能为空" => strings.isRequired(error.arguments[0]),
      "「{0}」必须是{1}" => strings.mustBe(
        error.arguments[0],
        _requirement(error.arguments[1]),
      ),
      "「{0}」的选项不能为空或包含首尾空白" => strings.optionsForCannotBeBlankOrBegin(
        error.arguments[0],
      ),
      "「{0}」的选项不能重复" => strings.optionsForMustBeUnique(error.arguments[0]),
      "「{0}」至少需要一个选项" => strings.requiresAtLeastOneOption(error.arguments[0]),
      "一个变更不能重复同一字段" => strings.aChangeCannotIncludeTheSameField,
      "会话不存在" => strings.chatNotFound,
      "分类必须属于有效的一级分类" => strings.chooseAValidTopLevelCategory,
      "同名标识的表已存在" => strings.aTableWithThisIdentifierAlreadyExists,
      "字段不存在" => strings.fieldNotFound,
      "字段名不能为空或包含首尾空白" => strings.fieldNamesCannotBeEmptyOrBegin,
      "字段名不能重复" => strings.fieldNamesMustBeUnique,
      "已有选项" => strings.anExistingOption,
      "待办 ID 已存在" => strings.taskIdAlreadyExists,
      "必填字段需要为现有记录补一个值" => strings.provideAValueForExistingRecordsBefore,
      "报告结束日期不能早于开始日期" => strings.endDateCannotPrecedeStartDate,
      "数据包含未定义的字段「{0}」" => strings.dataContainsAnUndefinedField(
        error.arguments[0],
      ),
      "数据类型不存在，请重新选择" => strings.dataTypeNoLongerExistsChooseAgain,
      "数据类型名称无效或重复" => strings.invalidOrDuplicateDataTypeName,
      "数据行 ID 无效或已存在" => strings.invalidOrDuplicateRowId,
      "数据行所属表不存在" => strings.parentTableNotFoundForRow,
      "数据表不存在或已归档" => strings.tableMissingOrArchived,
      "数据表所属类型不存在" => strings.tableTypeNotFound,
      "文本" => strings.text,
      "有效日期时间（yyyy-MM-dd HH:mm）" => strings.aValidDateAndTimeYyyyMm,
      "有效日期（yyyy-MM-dd）" => strings.aValidDateYyyyMmDd,
      "有限数字" => strings.aFiniteNumber,
      "消息 ID 已存在" => strings.messageIdAlreadyExists,
      "消息 ID 已用于另一会话" => strings.messageIdBelongsToAnotherChat,
      "消息不能移到其他会话" => strings.messagesCantBeMovedBetweenChats,
      "消息所属会话无效" => strings.invalidChatForThisMessage,
      "类型名称最多 20 个字" => strings.useUpToCharactersForTheTypeName,
      "类型名称最多 24 个字" => strings.useUpToCharactersForTheType,
      "至少保留一个字段" => strings.keepAtLeastOneField,
      "至少添加一个字段" => strings.addAtLeastOneField,
      "记录 ID 不能为空或重复" => strings.recordIdsCannotBeEmptyOrDuplicated,
      "记录已删除或不属于这张表，请重新确认" => strings.recordDeletedOrMovedToAnotherTable,
      "记录已有后续修改，无法撤销这次 AI 变更" => strings.recordChangedSinceThisAiUpdateUndo,
      "记录已有更新，请重新确认 AI 变更" => strings.recordUpdatedReviewTheAiChangesAgain,
      "记录的删除快照不完整，请重新确认" => strings.incompleteDeletionSnapshotReviewAgain,
      "该类型已存在" => strings.typeAlreadyExists,
      "这批 AI 变更已处理，请重新打开待确认记录" => strings.theseAiChangesHaveBeenProcessedReopen,
      "这条记录已删除" => strings.recordDeleted,
      "这条记录已存在，无法覆盖恢复" => strings.thisRecordAlreadyExistsAndCantBe,
      "选中的变更已不存在" => strings.theSelectedChangeNoLongerExists,
      _ => error.message,
    };

String _requirement(String value) => switch (value) {
  "文本" => strings.text,
  "有限数字" => strings.aFiniteNumber,
  "有效日期（yyyy-MM-dd）" => strings.aValidDateYyyyMmDd,
  "有效日期时间（yyyy-MM-dd HH:mm）" => strings.aValidDateAndTimeYyyyMm,
  "已有选项" => strings.anExistingOption,
  "true 或 false" => strings.trueOrFalse,
  _ => value,
};
